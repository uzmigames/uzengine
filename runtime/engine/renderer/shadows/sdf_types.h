/// UzEngine SDF Mesh Data Types — Per-Mesh Distance Field Storage
///
/// Defines the CPU-side data structures for sparse signed distance field
/// representations of static meshes. These are generated at asset import time
/// by the SDF baker and uploaded to the GPU atlas by `SdfAtlasManager`.
///
/// # Sparse Brick Layout
/// Each mesh SDF is divided into an 8x8x8 brick grid. Only bricks that intersect
/// the surface band (narrow band around the mesh surface) store voxel data —
/// empty-space and deep-interior bricks are represented as UINT32_MAX entries
/// in the indirection table. This typically reduces memory by 60-80% compared
/// to a dense 3D grid.
///
/// # Quantization
/// SDF values are stored as uint8_t with 128 representing the zero-crossing
/// (exact surface). Values below 128 are inside the mesh, above 128 are outside.
/// The quantization range depends on `MeshSdfAsset::voxelSize` — each step
/// represents `voxelSize / 128.0` cm of signed distance.
///
/// # UE5 Reference
/// - DistanceFieldAtlas.h:34-50 — brick layout, sparse storage
/// - DistanceFieldLightingShared.h:69-76 — per-object GPU data struct

#pragma once

#include <cstdint>
#include <vector>

namespace uz {

// ─────────────────────────────────────────────────────────────────────────────
// SdfBrick — single 8x8x8 voxel block of quantized SDF values
// ─────────────────────────────────────────────────────────────────────────────

/// A single 8x8x8 voxel block of quantized signed distance values.
///
/// Only bricks within the surface band are stored (sparse representation).
/// The voxel data is laid out in Z-major order: `data[z * 64 + y * 8 + x]`.
///
/// # Quantization
/// - 0: deep inside the mesh (most negative signed distance in the brick).
/// - 128: zero-crossing (exact surface).
/// - 255: farthest outside the mesh (most positive signed distance in the brick).
///
/// The actual signed distance in world units is:
/// `(float(data[i]) - 128.0f) * (voxelSize / 128.0f)`
///
/// # UE5 Reference
/// DistanceFieldAtlas.h:34-50 — brick dimensions and quantization scheme.
struct SdfBrick {
    static constexpr uint32_t kSize       = 8;     ///< Voxels per dimension.
    static constexpr uint32_t kVoxelCount = 512;   ///< Total voxels per brick (8 * 8 * 8).

    uint8_t data[kVoxelCount] = {};                ///< Quantized SDF values (128 = zero crossing).
};

static_assert(sizeof(SdfBrick) == 512, "SdfBrick must be exactly 512 bytes (8x8x8 uint8)");

// ─────────────────────────────────────────────────────────────────────────────
// MeshSdfAsset — per-mesh SDF data generated at import time
// ─────────────────────────────────────────────────────────────────────────────

/// Per-mesh signed distance field asset data.
///
/// Contains the sparse brick array and a flat 3D indirection table that maps
/// grid cells to brick indices. Generated by the SDF baker at asset import time,
/// serialized to `.uzsdf` files, and uploaded to the GPU atlas at runtime.
///
/// # Memory Layout
/// - `bricks`: Contiguous array of only the surface-band bricks.
/// - `indirection`: Flat 3D array of size `resolutionX * resolutionY * resolutionZ`.
///   Each entry is either a valid index into `bricks` or `UINT32_MAX` (empty cell).
///
/// # Resolution
/// Resolution values are in BRICKS, not individual voxels. The actual voxel
/// resolution is `resolution * SdfBrick::kSize` (e.g., 16 bricks = 128 voxels).
///
/// # Coordinate Convention
/// Local-space AABB uses the same Z-up, X-forward, left-handed system as the mesh.
/// `localBoundsMin/Max` define the axis-aligned box that encloses the mesh surface
/// plus a narrow-band margin of `voxelSize * SdfBrick::kSize / 2`.
struct MeshSdfAsset {
    float localBoundsMin[3] = {};    ///< Local-space AABB minimum (cm).
    float localBoundsMax[3] = {};    ///< Local-space AABB maximum (cm).
    float voxelSize         = 0.0f;  ///< World-space size of one voxel in cm.
    uint32_t resolutionX    = 0;     ///< Grid resolution X (in bricks, not voxels).
    uint32_t resolutionY    = 0;     ///< Grid resolution Y (in bricks).
    uint32_t resolutionZ    = 0;     ///< Grid resolution Z (in bricks).

    std::vector<SdfBrick>  bricks;       ///< Sparse brick data (surface-band bricks only) — MIP 0.
    std::vector<uint32_t>  indirection;  ///< Flat 3D indirection: grid index -> brick index (UINT32_MAX = empty) — MIP 0.

    /// MIP level data. Each MIP halves the brick resolution per axis.
    /// MIP 0 is stored in `bricks`/`indirection` above.
    /// `mipBricks[0]` = MIP 1 (4x4x4 voxels per brick), etc.
    ///
    /// # Downsample Algorithm
    /// Each 2x2x2 block of parent-MIP voxels is reduced to 1 voxel via
    /// minimum absolute distance (preserves the nearest surface).
    ///
    /// @source UE5 DistanceFieldAtlas.h — MIP chain for LOD tracing
    static constexpr uint32_t kMaxMipLevels = 3;

    struct MipLevel {
        std::vector<SdfBrick>  bricks;       ///< Sparse brick data for this MIP level.
        std::vector<uint32_t>  indirection;  ///< Flat 3D indirection for this MIP level.
        uint32_t resolutionX = 0;            ///< Brick resolution X at this MIP.
        uint32_t resolutionY = 0;            ///< Brick resolution Y at this MIP.
        uint32_t resolutionZ = 0;            ///< Brick resolution Z at this MIP.
    };

    MipLevel mipBricks[kMaxMipLevels];       ///< MIP levels 1-3 (MIP 0 is in bricks/indirection).
    uint32_t mipLevels = 1;                  ///< Number of MIP levels including base (1 = base only, 4 = base + 3 MIPs).

    /// Returns the total number of grid cells in the base indirection table.
    [[nodiscard]] uint32_t GetGridCellCount() const noexcept {
        return resolutionX * resolutionY * resolutionZ;
    }

    /// Returns the total number of bricks across all MIP levels.
    [[nodiscard]] uint32_t GetTotalBrickCount() const noexcept {
        uint32_t total = static_cast<uint32_t>(bricks.size());
        for (uint32_t m = 0; m < mipLevels - 1 && m < kMaxMipLevels; ++m) {
            total += static_cast<uint32_t>(mipBricks[m].bricks.size());
        }
        return total;
    }

    /// Returns true if the asset contains valid SDF data (non-zero resolution, non-empty bricks).
    [[nodiscard]] bool IsValid() const noexcept {
        return resolutionX > 0 && resolutionY > 0 && resolutionZ > 0
            && !bricks.empty()
            && indirection.size() == static_cast<size_t>(GetGridCellCount());
    }
};

// ─────────────────────────────────────────────────────────────────────────────
// SdfObjectGpuData — per-instance data uploaded to GPU StructuredBuffer
// ─────────────────────────────────────────────────────────────────────────────

/// Per-object SDF instance data for GPU consumption.
///
/// One entry per visible SDF object in the scene, uploaded to a StructuredBuffer
/// each frame. The tile culling compute shader reads this buffer to find which
/// objects overlap each screen tile, and the cone tracing shader uses it to
/// transform rays into the object's local SDF space.
///
/// # Alignment
/// Padded to 192 bytes (12 x float4) for efficient GPU StructuredBuffer access.
/// All float arrays use row-major 4x4 matrix layout for direct HLSL consumption.
/// World-space AABB is precomputed on CPU each frame to avoid per-pixel
/// matrix-AABB transform in the tile culling shader.
///
/// # UE5 Reference
/// DistanceFieldLightingShared.h:69-76 — FDFObjectData struct.
struct SdfObjectGpuData {
    // ── Row 0-3: 4x4 world-to-local transform (64 bytes) ──
    float    worldToLocal[16] = {};      ///< World -> local transform (row-major 4x4).

    // ── Row 4: local AABB min + padding (16 bytes) ──
    float    localBoundsMin[3] = {};     ///< Local-space AABB min (cm).
    float    pad0 = 0.0f;               ///< Pad to float4 boundary.

    // ── Row 5: local AABB max + padding (16 bytes) ──
    float    localBoundsMax[3] = {};     ///< Local-space AABB max (cm).
    float    pad1 = 0.0f;               ///< Pad to float4 boundary.

    // ── Row 6: world AABB min + padding (16 bytes) ──
    float    worldBoundsMin[3] = {};     ///< World-space AABB min (precomputed each frame).
    float    pad2 = 0.0f;               ///< Pad to float4 boundary.

    // ── Row 7: world AABB max + atlas offset (16 bytes) ──
    float    worldBoundsMax[3] = {};     ///< World-space AABB max (precomputed each frame).
    uint32_t atlasOffset = 0;            ///< Offset into SDF atlas texture (first brick index).

    // ── Row 8: voxel size + resolution (16 bytes) ──
    float    voxelSize = 0.0f;           ///< Voxel size in world units (cm).
    uint32_t resX = 0;                   ///< Grid resolution X in bricks.
    uint32_t resY = 0;                   ///< Grid resolution Y in bricks.
    uint32_t resZ = 0;                   ///< Grid resolution Z in bricks.

    // ── Rows 9-11: padding to 192 bytes (48 bytes) ──
    float    pad3[12] = {};              ///< Reserved for future use (e.g., LOD bias, flags).
};

static_assert(sizeof(SdfObjectGpuData) == 192, "SdfObjectGpuData must be 192 bytes (12 x float4)");

/// Sentinel value for empty indirection entries and unallocated atlas offsets.
static constexpr uint32_t kSdfIndirectionEmpty = UINT32_MAX;

} // namespace uz
