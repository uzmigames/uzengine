/// UzEngine Shader Parameter System — engine-style metadata-driven CB and resource binding.
///
/// Provides a reflection system for shader parameter structs. Each struct declares
/// which members are scalar data (copied into a constant buffer) and which are
/// resource handles (bound as SRV/sampler/UAV descriptors). The `ShaderParameterBinder`
/// uses this metadata to automatically upload CB data and bind resources per-pass.
///
/// # Design
/// Follows industry-standard's `SHADER_PARAMETER` macro pattern adapted for UzEngine:
/// - Scalar members are laid out first in the struct (contiguous, memcpy'd to CB).
/// - Resource handles follow the scalar section (not copied to CB).
/// - A static `GetMetadata()` method returns compile-time-generated descriptors.
///
/// # Usage
/// ```cpp
/// struct MyPassParams {
///     // Scalar section (copied to CB)
///     Mat4  viewProj;
///     Vec4  cameraPos;
///     float exposure;
///     float _pad[3];  // pad to 16-byte boundary
///
///     // Resource section (bound as SRV/sampler, NOT in CB)
///     RHITextureHandle envCubemap;
///     RHITextureHandle brdfLut;
///
///     static const ShaderParameterMetadata& GetMetadata();
/// };
/// ```
///
/// # Alignment
/// The `cbSize` field in metadata is always rounded up to 256 bytes (D3D12 CB
/// alignment requirement). Structs should pad their scalar section accordingly.
///
/// # See Also
/// - `shader_parameter_binder.h` — Binds a parameter struct to a command list.
/// - `constant_buffers.h` — Legacy manual CB definitions (being migrated).
/// - `cb_ring_allocator.h` — Ring-buffer allocator used by the binder.

#pragma once

#include "engine/rhi/rhi_types.h"

#include <cstddef>
#include <cstdint>

namespace uz {

// ─────────────────────────────────────────────────────────────────────────────
// ShaderParamType — discriminator for parameter member kinds
// ─────────────────────────────────────────────────────────────────────────────

/// Discriminates whether a shader parameter member is scalar data (goes into
/// the constant buffer) or a GPU resource handle (bound via SRV/sampler/UAV).
///
/// The binder uses this to decide: memcpy to CB ring (Scalar) or call
/// SetFragmentTexture/SetFragmentSampler (resource types).
enum class ShaderParamType : uint8_t {
    Scalar,      ///< float, uint32_t, Vec4, Mat4, etc. — copied into the CBV.
    Texture2D,   ///< RHITextureHandle — bound as SRV (Texture2D in HLSL).
    TextureCube, ///< RHITextureHandle — bound as SRV (TextureCube in HLSL).
    Sampler,     ///< RHISamplerHandle — bound as sampler.
    UAV,         ///< RHITextureHandle — bound as UAV.
};

// ─────────────────────────────────────────────────────────────────────────────
// ShaderParamMember — descriptor for a single struct member
// ─────────────────────────────────────────────────────────────────────────────

/// Describes a single member of a shader parameter struct.
///
/// For scalar members, `offset` and `size` describe the contiguous CB region.
/// For resource members, `offset` locates the RHI handle in the C++ struct
/// and `resourceSlot` determines the HLSL register slot (tN / sN / uN).
///
/// # Invariants
/// - Scalar members: `size > 0`, `resourceSlot == 0`.
/// - Resource members: `size == 0`, `resourceSlot` is the HLSL register index.
/// - `offset` is always a byte offset from the start of the enclosing struct.
struct ShaderParamMember {
    const char*     name;          ///< Member name (matches HLSL variable name for debugging).
    ShaderParamType type;          ///< Scalar, Texture2D, TextureCube, Sampler, or UAV.
    uint32_t        offset;        ///< Byte offset within the C++ struct.
    uint32_t        size;          ///< Byte size of the member (scalars only; 0 for resources).
    uint32_t        resourceSlot;  ///< HLSL register slot index (resources only; 0 for scalars).
};

// ─────────────────────────────────────────────────────────────────────────────
// ShaderParameterMetadata — aggregate descriptor for a parameter struct
// ─────────────────────────────────────────────────────────────────────────────

/// Compile-time metadata for a shader parameter struct.
///
/// Generated by the static `GetMetadata()` method on each parameter struct.
/// Consumed by `ShaderParameterBinder::Bind()` to automate CB upload and
/// resource binding.
///
/// # Fields
/// - `members` / `memberCount`: Full member array (scalars + resources).
/// - `cbSize`: Total size of the constant buffer portion, rounded up to 256 bytes.
///   The binder copies exactly `cbSize` bytes from offset 0 of the struct to the CB.
/// - `textureCount`, `samplerCount`, `uavCount`: Resource counts for validation.
///
/// # Thread Safety
/// Immutable after construction. Safe to share across threads.
struct ShaderParameterMetadata {
    const ShaderParamMember* members;       ///< Array of member descriptors (scalars first, then resources).
    uint32_t                 memberCount;   ///< Total number of members in the array.
    uint32_t                 cbSize;        ///< Constant buffer size in bytes (256-byte aligned).
    uint32_t                 textureCount;  ///< Number of Texture2D + TextureCube members.
    uint32_t                 samplerCount;  ///< Number of Sampler members.
    uint32_t                 uavCount;      ///< Number of UAV members.
};

// ─────────────────────────────────────────────────────────────────────────────
// Helper: 256-byte alignment for CB size calculation
// ─────────────────────────────────────────────────────────────────────────────

/// Rounds a byte size up to the nearest multiple of 256 (D3D12 CB alignment).
///
/// # Arguments
/// * `size` — Raw byte count.
///
/// # Returns
/// The smallest value >= `size` that is a multiple of 256.
[[nodiscard]] constexpr uint32_t AlignCBSize(uint32_t size) noexcept {
    return (size + 255u) & ~255u;
}

} // namespace uz
