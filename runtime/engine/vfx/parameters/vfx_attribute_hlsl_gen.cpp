#include "vfx_attribute_hlsl_gen.h"

#include <sstream>

namespace uz {

uint32_t VfxAttributeDefaultRegisterSlot(VfxAttributeScope scope) {
    switch (scope) {
        case VfxAttributeScope::System:    return 8u;
        case VfxAttributeScope::Emitter:   return 10u;
        case VfxAttributeScope::Particles: return 9u;
    }
    return 8u;
}

std::string GenerateVfxAttributeCbuffer(const VfxAttributeStore& store,
                                        const VfxAttributeHlslGenConfig& cfg) {
    const auto names = store.GetNames(cfg.scope);
    if (names.empty()) {
        return {};
    }

    const uint32_t slot = (cfg.registerSlot == 0xFFFFFFFFu)
                            ? VfxAttributeDefaultRegisterSlot(cfg.scope)
                            : cfg.registerSlot;

    const std::string scopeStr(VfxAttributeScopeToString(cfg.scope));

    std::string structName = cfg.structName;
    if (structName.empty()) {
        structName = "Vfx" + scopeStr + "Attributes";
    }

    std::ostringstream oss;
    // Header block
    oss << "// Auto-generated by VfxAttributeHlslGen — do not edit directly.\n";
    oss << "// Scope: " << scopeStr << ", register: b" << slot << ", attrs: "
        << names.size() << "\n";
    oss << "cbuffer " << structName << " : register(b" << slot << ") {\n";
    for (const auto& n : names) {
        oss << "    float4 _" << scopeStr << "_" << n << ";\n";
    }
    oss << "};\n\n";

    // Typed float4 accessor. Scalar / vec3 / vec4 specialisation is deferred
    // until the store records per-attribute type tags (phase7_7.2.0). For
    // now every accessor returns the packed float4; callers swizzle at use
    // sites, which mirrors the underlying Vec4 storage in VFXParameterStore.
    for (const auto& n : names) {
        oss << "float4 " << scopeStr << "_" << n
            << "() { return _" << scopeStr << "_" << n << "; }\n";
    }

    return oss.str();
}

} // namespace uz
