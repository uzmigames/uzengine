// ibl_baker.h -- GPU compute IBL baking pipeline.
//
// Replaces CPU-side sky_cubemap.cpp with GPU compute shader dispatches.
// Generates irradiance cubemap, prefiltered specular cubemap, and BRDF LUT
// using the RHI compute pipeline infrastructure.
//
// Usage:
//   IblBaker baker;
//   baker.init();  // creates compute PSOs (once at startup)
//   IblBakeResult result = baker.bake(skyParams);  // dispatch compute + return textures
//   baker.shutdown();

#pragma once

#include "engine/renderer/rhi/rhi.h"

namespace uz {

struct SkyCubemapParams; // forward decl from sky_cubemap.h

struct IblBakeResult {
    RhiTexture irradiance_cube;   // 32x32 per face, RGBA16F
    RhiTexture prefiltered_cube;  // 128x128 per face, 5 mip levels, RGBA16F
    RhiTexture brdf_lut;          // 256x256, RG16F
};

class IblBaker {
public:
    // Create compute PSOs. Call once at renderer init.
    bool init();

    // Destroy PSOs and cached resources.
    void shutdown();

    // Bake BRDF LUT (environment-independent, call once).
    RhiTexture bake_brdf_lut();

    // Bake irradiance + prefiltered cubemaps from a source environment cubemap.
    // The source cubemap must already exist (e.g., generated by sky_cubemap.cpp
    // or loaded from HDRI). Returns new texture handles.
    IblBakeResult bake(RhiTexture env_cubemap, uint32_t env_size);

private:
    RhiPipeline brdfLutPSO_    = RHI_NULL;
    RhiPipeline irradiancePSO_ = RHI_NULL;
    RhiPipeline prefilterPSO_  = RHI_NULL;
    bool initialized_ = false;
};

} // namespace uz
