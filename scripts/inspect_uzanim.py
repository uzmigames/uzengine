#!/usr/bin/env python3
"""Temporary debug inspector for .uzanim and .uzskel files.

Usage: python inspect_uzanim.py <clip.uzanim> <skeleton.uzskel>
Outputs a markdown report to stdout.
"""

import struct
import sys
import math
from pathlib import Path


UZ_ANIM_MAGIC = 0x4D4E415A  # 'ZANM'
UZ_ANIM_VERSION = 1
UZ_SKEL_MAGIC = 0x4B535A55  # 'UZSK'
UZ_SKEL_VERSION = 1


class Reader:
    def __init__(self, data):
        self.d = data
        self.o = 0

    def u8(self):
        v = self.d[self.o]
        self.o += 1
        return v

    def u16(self):
        v = struct.unpack_from("<H", self.d, self.o)[0]
        self.o += 2
        return v

    def i16(self):
        v = struct.unpack_from("<h", self.d, self.o)[0]
        self.o += 2
        return v

    def u32(self):
        v = struct.unpack_from("<I", self.d, self.o)[0]
        self.o += 4
        return v

    def f32(self):
        v = struct.unpack_from("<f", self.d, self.o)[0]
        self.o += 4
        return v

    def bytes_(self, n):
        v = self.d[self.o:self.o + n]
        self.o += n
        return v


def parse_anim(path):
    data = Path(path).read_bytes()
    r = Reader(data)
    magic = r.u32()
    version = r.u32()
    duration = r.f32()
    sample_rate = r.f32()
    chan_count = r.u32()
    flags = r.u32()
    name_len = r.u16()
    skel_name_len = r.u16()
    reserved = r.u32()
    name = r.bytes_(name_len).decode("utf-8", errors="replace")
    skel_name = r.bytes_(skel_name_len).decode("utf-8", errors="replace")

    channels = []
    for _ in range(chan_count):
        bn_len = r.u16()
        bone_name = r.bytes_(bn_len).decode("utf-8", errors="replace")
        pos_count = r.u32()
        rot_count = r.u32()
        scl_count = r.u32()

        pos_keys = [(r.f32(), r.f32(), r.f32(), r.f32()) for _ in range(pos_count)]
        rot_keys = [(r.f32(), r.f32(), r.f32(), r.f32(), r.f32()) for _ in range(rot_count)]
        scl_keys = [(r.f32(), r.f32(), r.f32(), r.f32()) for _ in range(scl_count)]

        channels.append({
            "bone": bone_name,
            "pos": pos_keys,   # (t, x, y, z)
            "rot": rot_keys,   # (t, x, y, z, w)
            "scl": scl_keys,   # (t, x, y, z)
        })

    return {
        "header_raw": data[:32],
        "size": len(data),
        "magic": magic,
        "version": version,
        "duration": duration,
        "sample_rate": sample_rate,
        "channel_count": chan_count,
        "flags": flags,
        "name": name,
        "skel_name": skel_name,
        "channels": channels,
        "consumed": r.o,
    }


def parse_skel(path):
    data = Path(path).read_bytes()
    r = Reader(data)
    magic = r.u32()
    version = r.u32()
    bone_count = r.u32()
    reserved = r.u32()

    bones = []
    for i in range(bone_count):
        nl = r.u16()
        name = r.bytes_(nl).decode("utf-8", errors="replace")
        parent = r.i16()
        tx, ty, tz = r.f32(), r.f32(), r.f32()
        qx, qy, qz, qw = r.f32(), r.f32(), r.f32(), r.f32()
        sx, sy, sz = r.f32(), r.f32(), r.f32()
        bones.append({
            "index": i,
            "name": name,
            "parent": parent,
            "translation": (tx, ty, tz),
            "rotation": (qx, qy, qz, qw),
            "scale": (sx, sy, sz),
        })

    return {
        "magic": magic,
        "version": version,
        "bone_count": bone_count,
        "bones": bones,
    }


def hex_dump(data, n=64):
    lines = []
    for i in range(0, min(len(data), n), 16):
        chunk = data[i:i+16]
        hex_part = " ".join(f"{b:02X}" for b in chunk)
        ascii_part = "".join((chr(b) if 32 <= b < 127 else ".") for b in chunk)
        lines.append(f"  {i:04X}  {hex_part:<48}  {ascii_part}")
    return "\n".join(lines)


def is_finite(*vals):
    return all(math.isfinite(v) for v in vals)


def is_nan_inf(v):
    return (not math.isfinite(v))


def quat_len(q):
    x, y, z, w = q
    return math.sqrt(x*x + y*y + z*z + w*w)


def vec_len(v):
    x, y, z = v
    return math.sqrt(x*x + y*y + z*z)


def report(anim, skel, out):
    p = lambda *a, **kw: print(*a, file=out, **kw)

    p("# Mushroom_Idle .uzanim Inspection Report")
    p()
    p("Temporary debug analysis. Generated by `scripts/inspect_uzanim.py`.")
    p()
    p(f"- Clip file size: **{anim['size']} bytes**")
    p(f"- Bytes consumed by parser: **{anim['consumed']}**")
    p(f"- Trailing bytes: **{anim['size'] - anim['consumed']}**")
    p()

    # 1. Hex dump
    p("## 1. Header hex dump (first 64 bytes)")
    p()
    p("```")
    p(hex_dump(anim['header_raw'], 64))
    p("```")
    p()
    magic_ok = anim['magic'] == UZ_ANIM_MAGIC
    ver_ok = anim['version'] == UZ_ANIM_VERSION
    magic_chars = struct.pack("<I", anim['magic']).decode("ascii", errors="replace")
    p(f"- Magic: `0x{anim['magic']:08X}` (`{magic_chars}`) — {'OK (ZANM)' if magic_ok else 'BAD'}")
    p(f"- Version: `{anim['version']}` — {'OK' if ver_ok else 'BAD'}")
    p(f"- Duration: `{anim['duration']:.6f}` s")
    p(f"- Sample rate: `{anim['sample_rate']:.4f}` fps")
    p(f"- Channel count: `{anim['channel_count']}`")
    p(f"- Flags: `0x{anim['flags']:08X}` (loop = {(anim['flags'] & 1) != 0})")
    p(f"- Clip name: `'{anim['name']}'`")
    p(f"- Skeleton name: `'{anim['skel_name']}'`")
    p()

    # 2. List all channels with key counts
    p("## 2. Channel keyframe counts")
    p()
    p("| # | Bone | Pos | Rot | Scl |")
    p("|---|------|-----|-----|-----|")
    for i, ch in enumerate(anim['channels']):
        p(f"| {i} | `{ch['bone']}` | {len(ch['pos'])} | {len(ch['rot'])} | {len(ch['scl'])} |")
    p()

    # 3. Representative bones: root, mid-chain, leaf — first/last keyframes
    p("## 3. First / last keyframes for representative bones")
    p()

    # Pick representatives by index in skeleton ordering
    n = len(anim['channels'])
    if n == 0:
        p("No channels.")
    else:
        rep_idx = sorted(set([0, n // 2, n - 1]))
        # Also try to find well-known names
        for i in rep_idx:
            ch = anim['channels'][i]
            p(f"### Channel {i}: `{ch['bone']}`")
            p()

            def dump_keys(label, keys, fmt):
                if not keys:
                    p(f"- {label}: empty")
                    return
                k0 = keys[0]
                kN = keys[-1]
                p(f"- {label} ({len(keys)} keys):")
                p(f"  - first @ t={k0[0]:.4f}: {fmt(k0[1:])}")
                p(f"  - last  @ t={kN[0]:.4f}: {fmt(kN[1:])}")

            def fmt_v(v):
                return f"({v[0]:+.4f}, {v[1]:+.4f}, {v[2]:+.4f})"

            def fmt_q(v):
                ql = quat_len(v)
                return f"({v[0]:+.4f}, {v[1]:+.4f}, {v[2]:+.4f}, {v[3]:+.4f})  |q|={ql:.4f}"

            dump_keys("Position (cm)", ch['pos'], fmt_v)
            dump_keys("Rotation",      ch['rot'], fmt_q)
            dump_keys("Scale",         ch['scl'], fmt_v)
            p()

    # 4. Anomaly scan
    p("## 4. Anomaly scan (entire clip)")
    p()
    pos_oor = []  # > 1000 cm
    scl_oor = []  # outside [0.5, 2.0]
    quat_bad = []  # |q| outside [0.99, 1.01]
    nan_inf = []
    non_uniform_scale = []  # any axis differing from another by >0.001

    for ch in anim['channels']:
        for k in ch['pos']:
            t, x, y, z = k
            if not is_finite(t, x, y, z):
                nan_inf.append((ch['bone'], 'pos', t, (x, y, z)))
                continue
            if vec_len((x, y, z)) > 1000.0:
                pos_oor.append((ch['bone'], t, (x, y, z), vec_len((x, y, z))))
        for k in ch['rot']:
            t, qx, qy, qz, qw = k
            if not is_finite(t, qx, qy, qz, qw):
                nan_inf.append((ch['bone'], 'rot', t, (qx, qy, qz, qw)))
                continue
            ql = quat_len((qx, qy, qz, qw))
            if ql < 0.99 or ql > 1.01:
                quat_bad.append((ch['bone'], t, (qx, qy, qz, qw), ql))
        for k in ch['scl']:
            t, sx, sy, sz = k
            if not is_finite(t, sx, sy, sz):
                nan_inf.append((ch['bone'], 'scl', t, (sx, sy, sz)))
                continue
            if sx < 0.5 or sx > 2.0 or sy < 0.5 or sy > 2.0 or sz < 0.5 or sz > 2.0:
                scl_oor.append((ch['bone'], t, (sx, sy, sz)))
            d_xy = abs(sx - sy)
            d_yz = abs(sy - sz)
            d_xz = abs(sx - sz)
            if max(d_xy, d_yz, d_xz) > 0.001:
                non_uniform_scale.append((ch['bone'], t, (sx, sy, sz),
                                          max(d_xy, d_yz, d_xz)))

    def section(name, items, formatter, max_show=20):
        p(f"### {name}: **{len(items)}** matches")
        if not items:
            p()
            p("- (none)")
            p()
            return
        p()
        for it in items[:max_show]:
            p(f"- {formatter(it)}")
        if len(items) > max_show:
            p(f"- ... (+{len(items) - max_show} more)")
        p()

    section("Position magnitude > 1000 cm",
            pos_oor,
            lambda x: f"`{x[0]}` t={x[1]:.3f} pos=({x[2][0]:+.2f},{x[2][1]:+.2f},{x[2][2]:+.2f}) |p|={x[3]:.2f}")

    section("Scale outside [0.5, 2.0]",
            scl_oor,
            lambda x: f"`{x[0]}` t={x[1]:.3f} scl=({x[2][0]:+.4f},{x[2][1]:+.4f},{x[2][2]:+.4f})")

    section("Quaternion |q| outside [0.99, 1.01]",
            quat_bad,
            lambda x: f"`{x[0]}` t={x[1]:.3f} q=({x[2][0]:+.4f},{x[2][1]:+.4f},{x[2][2]:+.4f},{x[2][3]:+.4f}) |q|={x[3]:.4f}")

    section("NaN / Inf values",
            nan_inf,
            lambda x: f"`{x[0]}` channel={x[1]} t={x[2]} val={x[3]}")

    section("Non-uniform scale (max axis diff > 0.001)",
            non_uniform_scale,
            lambda x: f"`{x[0]}` t={x[1]:.3f} scl=({x[2][0]:+.4f},{x[2][1]:+.4f},{x[2][2]:+.4f}) maxDiff={x[3]:.4f}",
            max_show=30)

    # 5. Compare keyframe[0] to bind transforms in skeleton
    p("## 5. Keyframe[0] vs. bind-pose comparison")
    p()
    p(f"Skeleton: `{skel['bone_count']}` bones, magic=0x{skel['magic']:08X} version={skel['version']}")
    p()
    p("Per-bone delta = (keyframe[0] value) − (bind value).")
    p("LARGE deltas (translation > 1 cm, quat dot < 0.99, scale diff > 0.01) flagged.")
    p()
    p("| Bone | Δpos (cm) |Δp| | bind pos | key0 pos | quat·dot | scl bind | scl key0 |")
    p("|------|-----------|-----|----------|----------|----------|----------|----------|")

    # Build name → bind map
    bind_by_name = {b['name']: b for b in skel['bones']}

    flagged_count = 0
    rows = []

    for ch in anim['channels']:
        bone_name = ch['bone']
        bind = bind_by_name.get(bone_name)
        if bind is None:
            rows.append((bone_name, "MISSING IN SKELETON", None, None, None, None, None, None, True))
            flagged_count += 1
            continue

        # Position
        if ch['pos']:
            kp = ch['pos'][0][1:]
        else:
            kp = bind['translation']
        bp = bind['translation']
        dx = kp[0] - bp[0]
        dy = kp[1] - bp[1]
        dz = kp[2] - bp[2]
        dpos_mag = math.sqrt(dx*dx + dy*dy + dz*dz)

        # Rotation: dot product (abs, since q == -q)
        if ch['rot']:
            kq = ch['rot'][0][1:]
        else:
            kq = bind['rotation']
        bq = bind['rotation']
        dot = abs(kq[0]*bq[0] + kq[1]*bq[1] + kq[2]*bq[2] + kq[3]*bq[3])

        # Scale
        if ch['scl']:
            ks = ch['scl'][0][1:]
        else:
            ks = bind['scale']
        bs = bind['scale']
        scl_diff = max(abs(ks[i] - bs[i]) for i in range(3))

        flag = False
        if dpos_mag > 1.0 or dot < 0.99 or scl_diff > 0.01:
            flag = True
            flagged_count += 1

        rows.append((bone_name,
                     f"({dx:+.2f},{dy:+.2f},{dz:+.2f})",
                     f"{dpos_mag:.2f}",
                     f"({bp[0]:+.2f},{bp[1]:+.2f},{bp[2]:+.2f})",
                     f"({kp[0]:+.2f},{kp[1]:+.2f},{kp[2]:+.2f})",
                     f"{dot:.4f}",
                     f"({bs[0]:.3f},{bs[1]:.3f},{bs[2]:.3f})",
                     f"({ks[0]:.3f},{ks[1]:.3f},{ks[2]:.3f})",
                     flag))

    # Print all flagged first, then a summary count
    for r in rows:
        marker = " ⚠" if r[8] else ""
        if r[2] is None:
            p(f"| `{r[0]}` | (bone missing in skeleton) |  |  |  |  |  |  |{marker}")
        else:
            p(f"| `{r[0]}` | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} | {r[7]} |{marker}")

    p()
    p(f"**Bones flagged as significantly deviating from bind: {flagged_count} / {len(anim['channels'])}**")
    p()

    # Skeleton bones not present in clip
    clip_names = {ch['bone'] for ch in anim['channels']}
    missing_in_clip = [b['name'] for b in skel['bones'] if b['name'] not in clip_names]
    if missing_in_clip:
        p(f"**Skeleton bones with no animation channel:** {len(missing_in_clip)}")
        for n in missing_in_clip:
            p(f"- `{n}`")
        p()


def main():
    if len(sys.argv) < 4:
        print("Usage: inspect_uzanim.py <clip.uzanim> <skeleton.uzskel> <output.md>", file=sys.stderr)
        sys.exit(1)

    clip_path = sys.argv[1]
    skel_path = sys.argv[2]
    out_path = sys.argv[3]

    anim = parse_anim(clip_path)
    if anim['magic'] != UZ_ANIM_MAGIC:
        print(f"WARNING: bad magic 0x{anim['magic']:08X} in {clip_path}", file=sys.stderr)
    if anim['version'] != UZ_ANIM_VERSION:
        print(f"WARNING: bad version {anim['version']} in {clip_path}", file=sys.stderr)

    skel = parse_skel(skel_path)

    with open(out_path, "w", encoding="utf-8") as f:
        report(anim, skel, f)

    print(f"Wrote report to {out_path}")


if __name__ == "__main__":
    main()
